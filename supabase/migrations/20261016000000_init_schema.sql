-- ---------------------------------------------------------------------------
-- RPC: save_menu_analysis（P0版。所有者引数なし・利用者同意は常にfalse）
-- ---------------------------------------------------------------------------

-- メニュー1件と料理1〜20件を1トランザクションで登録し、menu_id を返す。
-- 料理は p_dishes の配列順を1始まりの position として保存する。
create function public.save_menu_analysis(
  p_restaurant_id uuid,
  p_image_path text,
  p_analysis_token_hash text,
  p_dishes jsonb,
  p_ai_model text,
  p_prompt_version text,
  p_analysis_expires_at timestamptz default null
)
returns uuid
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_menu_id uuid;
  v_dish jsonb;
  v_count integer;
begin
  if p_analysis_token_hash is null or p_analysis_token_hash !~ '^[0-9a-f]{64}$' then
    raise exception 'invalid_analysis_token_hash' using errcode = '22023';
  end if;

  if p_dishes is null or jsonb_typeof(p_dishes) <> 'array' then
    raise exception 'dishes_invalid' using errcode = '22023';
  end if;

  v_count := jsonb_array_length(p_dishes);
  if v_count < 1 or v_count > 20 then
    raise exception 'dishes_invalid' using errcode = '22023';
  end if;

  for v_dish in select e.value from jsonb_array_elements(p_dishes) as e(value) loop
    if jsonb_typeof(v_dish) <> 'object' then
      raise exception 'dishes_invalid' using errcode = '22023';
    end if;
    if exists (
         select 1
           from jsonb_object_keys(v_dish) as k(key)
          where k.key not in ('name', 'name_key', 'translations', 'price', 'currency', 'ai_result')
       )
       or jsonb_typeof(v_dish -> 'name') is distinct from 'string'
       or jsonb_typeof(v_dish -> 'name_key') is distinct from 'string'
       or jsonb_typeof(v_dish -> 'translations') is distinct from 'object'
       or jsonb_typeof(v_dish -> 'ai_result') is distinct from 'object'
       or coalesce(jsonb_typeof(v_dish -> 'price'), 'null') not in ('number', 'null')
       or coalesce(jsonb_typeof(v_dish -> 'currency'), 'null') not in ('string', 'null')
    then
      raise exception 'dishes_invalid' using errcode = '22023';
    end if;
  end loop;

  insert into public.menus (
    restaurant_id,
    user_publish_consent,
    image_path,
    analysis_token_hash,
    analysis_expires_at
  )
  values (
    p_restaurant_id,
    false,
    p_image_path,
    p_analysis_token_hash,
    coalesce(p_analysis_expires_at, now() + interval '24 hours')
  )
  returning id into v_menu_id;

  insert into public.dishes (
    menu_id,
    name,
    position,
    name_key,
    translations,
    price,
    currency,
    ai_result,
    ai_model,
    prompt_version
  )
  select
    v_menu_id,
    e.value ->> 'name',
    e.ordinality::smallint,
    e.value ->> 'name_key',
    e.value -> 'translations',
    (e.value ->> 'price')::numeric(10, 2),
    coalesce(e.value ->> 'currency', 'JPY'),
    e.value -> 'ai_result',
    p_ai_model,
    p_prompt_version
  from jsonb_array_elements(p_dishes) with ordinality as e(value, ordinality);

  return v_menu_id;
end;
$$;

-- ---------------------------------------------------------------------------
-- RPC: complete_confirmation_session
-- ---------------------------------------------------------------------------

-- 店員の公開可否とアレルゲン・食事制限の全回答を1回の呼び出しで保存する。
-- 同じ request_id の再送は、両配列を項目順に正規化して公開可否とともに比較する。
create function public.complete_confirmation_session(
  p_menu_id uuid,
  p_analysis_token_hash text,
  p_request_id uuid,
  p_answers jsonb,
  p_dietary_answers jsonb,
  p_publish_consent boolean,
  out session_id uuid,
  out confirmed_at timestamptz,
  out replayed boolean
)
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_menu public.menus%rowtype;
  v_item jsonb;
  v_answers jsonb := '[]'::jsonb;
  v_dietary jsonb := '[]'::jsonb;
  v_total integer;
  v_answer_count integer;
  v_answer_dishes integer;
  v_answer_items integer;
  v_dietary_count integer;
  v_dietary_dishes integer;
  v_dietary_items integer;
  v_union_dishes integer;
  v_existing public.confirmation_sessions%rowtype;
  v_session_id uuid;
  v_confirmed_at timestamptz;
begin
  -- 1. メニューをロックし、トークンと期限を検証する。
  select m.*
    into v_menu
    from public.menus m
   where m.id = p_menu_id
     for update;
  if not found then
    raise exception 'menu_not_found' using errcode = 'P0002';
  end if;

  if p_analysis_token_hash is null
     or p_analysis_token_hash !~ '^[0-9a-f]{64}$'
     or p_analysis_token_hash <> v_menu.analysis_token_hash then
    raise exception 'invalid_analysis_token' using errcode = '28000';
  end if;

  if v_menu.analysis_expires_at <= now() then
    raise exception 'analysis_expired' using errcode = 'P0003';
  end if;

  -- 2. 入力を検証する。欠落・nullは未回答として拒否し、明示的な unknown は許可する。
  if p_request_id is null or p_publish_consent is null then
    raise exception 'validation_error' using errcode = '22023';
  end if;

  if p_answers is null or jsonb_typeof(p_answers) <> 'array'
     or p_dietary_answers is null or jsonb_typeof(p_dietary_answers) <> 'array' then
    raise exception 'answers_invalid' using errcode = '22023';
  end if;

  v_total := jsonb_array_length(p_answers) + jsonb_array_length(p_dietary_answers);
  if v_total < 1 or v_total > 50 then
    raise exception 'answers_invalid' using errcode = '22023';
  end if;

  for v_item in select e.value from jsonb_array_elements(p_answers) as e(value) loop
    if jsonb_typeof(v_item) <> 'object' then
      raise exception 'answers_invalid' using errcode = '22023';
    end if;
    if (select count(*) from jsonb_object_keys(v_item)) <> 3
       or not (v_item ?& array['dish_id', 'allergen_id', 'answer'])
       or jsonb_typeof(v_item -> 'dish_id') is distinct from 'string'
       or (v_item ->> 'dish_id') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
       or jsonb_typeof(v_item -> 'allergen_id') is distinct from 'number'
       or (v_item ->> 'allergen_id') !~ '^[0-9]{1,4}$'
       or jsonb_typeof(v_item -> 'answer') is distinct from 'string'
       or (v_item ->> 'answer') not in ('contains', 'cross_contact', 'not_contains', 'unknown')
    then
      raise exception 'answers_invalid' using errcode = '22023';
    end if;
    v_answers := v_answers || jsonb_build_array(jsonb_build_object(
      'dish_id', (v_item ->> 'dish_id')::uuid,
      'item_id', (v_item ->> 'allergen_id')::smallint,
      'answer', v_item ->> 'answer'
    ));
  end loop;

  for v_item in select e.value from jsonb_array_elements(p_dietary_answers) as e(value) loop
    if jsonb_typeof(v_item) <> 'object' then
      raise exception 'answers_invalid' using errcode = '22023';
    end if;
    if (select count(*) from jsonb_object_keys(v_item)) <> 3
       or not (v_item ?& array['dish_id', 'dietary_restriction_id', 'answer'])
       or jsonb_typeof(v_item -> 'dish_id') is distinct from 'string'
       or (v_item ->> 'dish_id') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
       or jsonb_typeof(v_item -> 'dietary_restriction_id') is distinct from 'number'
       or (v_item ->> 'dietary_restriction_id') !~ '^[0-9]{1,4}$'
       or jsonb_typeof(v_item -> 'answer') is distinct from 'string'
       or (v_item ->> 'answer') not in ('not_supported', 'supported', 'cross_contact', 'unknown')
    then
      raise exception 'answers_invalid' using errcode = '22023';
    end if;
    v_dietary := v_dietary || jsonb_build_array(jsonb_build_object(
      'dish_id', (v_item ->> 'dish_id')::uuid,
      'item_id', (v_item ->> 'dietary_restriction_id')::smallint,
      'answer', v_item ->> 'answer'
    ));
  end loop;

  -- 重複（同じ料理×同じ項目）
  if exists (
       select 1
         from jsonb_to_recordset(v_answers) as a(dish_id uuid, item_id smallint, answer text)
        group by a.dish_id, a.item_id
       having count(*) > 1
     )
     or exists (
       select 1
         from jsonb_to_recordset(v_dietary) as a(dish_id uuid, item_id smallint, answer text)
        group by a.dish_id, a.item_id
       having count(*) > 1
     ) then
    raise exception 'answers_invalid' using errcode = '22023';
  end if;

  -- 未知の項目ID
  if exists (
       select 1
         from jsonb_to_recordset(v_answers) as a(dish_id uuid, item_id smallint, answer text)
        where not exists (select 1 from public.allergens x where x.id = a.item_id)
     )
     or exists (
       select 1
         from jsonb_to_recordset(v_dietary) as a(dish_id uuid, item_id smallint, answer text)
        where not exists (select 1 from public.dietary_restrictions x where x.id = a.item_id)
     ) then
    raise exception 'answers_invalid' using errcode = '22023';
  end if;

  -- 料理の和集合は1〜10件
  select count(distinct u.dish_id)
    into v_union_dishes
    from (
      select a.dish_id from jsonb_to_recordset(v_answers) as a(dish_id uuid, item_id smallint, answer text)
      union all
      select a.dish_id from jsonb_to_recordset(v_dietary) as a(dish_id uuid, item_id smallint, answer text)
    ) as u;
  if v_union_dishes < 1 or v_union_dishes > 10 then
    raise exception 'answers_invalid' using errcode = '22023';
  end if;

  -- 料理がこのメニューに属すること
  if exists (
       select 1
         from (
           select a.dish_id from jsonb_to_recordset(v_answers) as a(dish_id uuid, item_id smallint, answer text)
           union
           select a.dish_id from jsonb_to_recordset(v_dietary) as a(dish_id uuid, item_id smallint, answer text)
         ) as u
        where not exists (
          select 1 from public.dishes d where d.id = u.dish_id and d.menu_id = p_menu_id
        )
     ) then
    raise exception 'dish_not_in_menu' using errcode = '22023';
  end if;

  -- 各配列は料理集合×項目集合の直積をちょうど1回ずつ含む（重複は上で拒否済み）
  select count(*), count(distinct a.dish_id), count(distinct a.item_id)
    into v_answer_count, v_answer_dishes, v_answer_items
    from jsonb_to_recordset(v_answers) as a(dish_id uuid, item_id smallint, answer text);
  select count(*), count(distinct a.dish_id), count(distinct a.item_id)
    into v_dietary_count, v_dietary_dishes, v_dietary_items
    from jsonb_to_recordset(v_dietary) as a(dish_id uuid, item_id smallint, answer text);

  if v_answer_count <> v_answer_dishes * v_answer_items
     or v_dietary_count <> v_dietary_dishes * v_dietary_items then
    raise exception 'answers_invalid' using errcode = '22023';
  end if;

  -- 両配列に回答がある場合は料理集合を一致させる
  if v_answer_count > 0 and v_dietary_count > 0 and exists (
       (select a.dish_id from jsonb_to_recordset(v_answers) as a(dish_id uuid, item_id smallint, answer text)
        except
        select a.dish_id from jsonb_to_recordset(v_dietary) as a(dish_id uuid, item_id smallint, answer text))
       union all
       (select a.dish_id from jsonb_to_recordset(v_dietary) as a(dish_id uuid, item_id smallint, answer text)
        except
        select a.dish_id from jsonb_to_recordset(v_answers) as a(dish_id uuid, item_id smallint, answer text))
     ) then
    raise exception 'answers_invalid' using errcode = '22023';
  end if;

  -- 3. 同じ request_id の再送判定（上限判定より先に行う）
  select s.*
    into v_existing
    from public.confirmation_sessions s
   where s.menu_id = p_menu_id
     and s.request_id = p_request_id;
  if found then
    if v_existing.publish_consent = p_publish_consent
       and (
         select coalesce(jsonb_agg(jsonb_build_array(ca.dish_id, ca.allergen_id, ca.answer)
                                   order by ca.dish_id, ca.allergen_id), '[]'::jsonb)
           from public.confirmation_answers ca
          where ca.session_id = v_existing.id
       ) = (
         select coalesce(jsonb_agg(jsonb_build_array(a.dish_id, a.item_id, a.answer)
                                   order by a.dish_id, a.item_id), '[]'::jsonb)
           from jsonb_to_recordset(v_answers) as a(dish_id uuid, item_id smallint, answer text)
       )
       and (
         select coalesce(jsonb_agg(jsonb_build_array(cd.dish_id, cd.dietary_restriction_id, cd.answer)
                                   order by cd.dish_id, cd.dietary_restriction_id), '[]'::jsonb)
           from public.confirmation_dietary_answers cd
          where cd.session_id = v_existing.id
       ) = (
         select coalesce(jsonb_agg(jsonb_build_array(a.dish_id, a.item_id, a.answer)
                                   order by a.dish_id, a.item_id), '[]'::jsonb)
           from jsonb_to_recordset(v_dietary) as a(dish_id uuid, item_id smallint, answer text)
       )
    then
      session_id := v_existing.id;
      confirmed_at := v_existing.created_at;
      replayed := true;
      return;
    end if;
    raise exception 'request_id_conflict' using errcode = '40001';
  end if;

  -- 4. 新規の確認にだけ1メニュー5回の上限を適用する
  if (select count(*) from public.confirmation_sessions s where s.menu_id = p_menu_id) >= 5 then
    raise exception 'confirmation_limit_reached' using errcode = '22023';
  end if;

  insert into public.confirmation_sessions (menu_id, restaurant_id, request_id, publish_consent)
  values (p_menu_id, v_menu.restaurant_id, p_request_id, p_publish_consent)
  returning id, created_at into v_session_id, v_confirmed_at;

  insert into public.confirmation_answers (session_id, dish_id, allergen_id, dish_version, answer)
  select v_session_id, a.dish_id, a.item_id, d.version, a.answer
    from jsonb_to_recordset(v_answers) as a(dish_id uuid, item_id smallint, answer text)
    join public.dishes d on d.id = a.dish_id;

  insert into public.confirmation_dietary_answers (session_id, dish_id, dietary_restriction_id, dish_version, answer)
  select v_session_id, a.dish_id, a.item_id, d.version, a.answer
    from jsonb_to_recordset(v_dietary) as a(dish_id uuid, item_id smallint, answer text)
    join public.dishes d on d.id = a.dish_id;

  -- 5. session_id・confirmed_at・replayed を返す
  session_id := v_session_id;
  confirmed_at := v_confirmed_at;
  replayed := false;
end;
$$;

