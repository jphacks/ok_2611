create view public.published_menus
with (security_invoker = true)
as
select
  m.id as menu_id,
  m.restaurant_id,
  r.google_place_id,
  m.created_at as scanned_at,
  p.published_at,
  d.id as dish_id,
  d.name as dish_name,
  d.name_key,
  d.translations,
  d.price,
  d.currency,
  d.version as dish_version,
  d.ai_result
from public.menus m
join public.restaurants r on r.id = m.restaurant_id
join (
  select s.menu_id, max(s.created_at) as published_at
    from public.confirmation_sessions s
   where s.publish_consent
   group by s.menu_id
) p on p.menu_id = m.id
join public.dishes d on d.menu_id = m.id
where m.user_publish_consent;

create view public.published_confirmation_answers
with (security_invoker = true)
as
select
  s.id as session_id,
  m.restaurant_id,
  r.google_place_id,
  m.id as menu_id,
  a.dish_id,
  d.name_key,
  a.dish_version,
  a.allergen_id,
  a.answer,
  s.created_at as confirmed_at
from public.confirmation_answers a
join public.confirmation_sessions s on s.id = a.session_id
join public.menus m on m.id = s.menu_id
join public.restaurants r on r.id = m.restaurant_id
join public.dishes d on d.id = a.dish_id
where s.publish_consent
  and m.user_publish_consent;

create view public.published_dietary_answers
with (security_invoker = true)
as
select
  s.id as session_id,
  m.restaurant_id,
  r.google_place_id,
  m.id as menu_id,
  a.dish_id,
  d.name_key,
  a.dish_version,
  a.dietary_restriction_id,
  a.answer,
  s.created_at as confirmed_at
from public.confirmation_dietary_answers a
join public.confirmation_sessions s on s.id = a.session_id
join public.menus m on m.id = s.menu_id
join public.restaurants r on r.id = m.restaurant_id
join public.dishes d on d.id = a.dish_id
where s.publish_consent
  and m.user_publish_consent;

