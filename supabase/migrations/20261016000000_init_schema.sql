-- 作成後のスナップショットの更新を拒否する。
create function public.reject_snapshot_update()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  raise exception 'snapshot_is_immutable' using errcode = '55000';
end;
$$;

-- 確認の店舗がメニューの店舗と一致すること、1メニューあたり5件以内であることを確認する。
-- メニュー行をロックし、RPCを経由しない挿入でも上限判定を直列化する。
create function public.validate_confirmation_session()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_restaurant_id uuid;
  v_count integer;
begin
  select m.restaurant_id
    into v_restaurant_id
    from public.menus m
   where m.id = new.menu_id
     for update;
  if not found then
    -- 存在しないメニューは外部キー制約で拒否する。
    return new;
  end if;

  if new.restaurant_id is distinct from v_restaurant_id then
    raise exception 'restaurant_mismatch' using errcode = '22023';
  end if;

  select count(*)
    into v_count
    from public.confirmation_sessions s
   where s.menu_id = new.menu_id;
  if v_count >= 5 then
    raise exception 'confirmation_limit_reached' using errcode = '22023';
  end if;

  return new;
end;
$$;

-- 回答の料理が確認と同じメニューに属し、料理の版が一致することを確認する。
-- confirmation_answers・confirmation_dietary_answers で共用する。
create function public.validate_confirmation_answer()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_session_menu_id uuid;
  v_dish_menu_id uuid;
  v_dish_version integer;
begin
  select s.menu_id
    into v_session_menu_id
    from public.confirmation_sessions s
   where s.id = new.session_id;

  select d.menu_id, d.version
    into v_dish_menu_id, v_dish_version
    from public.dishes d
   where d.id = new.dish_id;

  if v_session_menu_id is null or v_dish_menu_id is null then
    -- 存在しない確認・料理は外部キー制約で拒否する。
    return new;
  end if;

  if v_dish_menu_id <> v_session_menu_id then
    raise exception 'dish_not_in_menu' using errcode = '22023';
  end if;

  if new.dish_version is distinct from v_dish_version then
    raise exception 'dish_version_mismatch' using errcode = '22023';
  end if;

  return new;
end;
$$;

