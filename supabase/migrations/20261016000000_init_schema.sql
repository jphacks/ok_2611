create table public.restaurants (
  id uuid primary key default gen_random_uuid(),
  google_place_id text not null unique
    check (char_length(google_place_id) between 1 and 255),
  created_at timestamptz not null default now()
);

create table public.menus (
  id uuid primary key default gen_random_uuid(),
  restaurant_id uuid references public.restaurants (id) on delete restrict,
  user_publish_consent boolean not null default false,
  image_path text not null unique
    check (char_length(image_path) >= 1),
  analysis_token_hash text not null unique
    check (analysis_token_hash ~ '^[0-9a-f]{64}$'),
  analysis_expires_at timestamptz not null default (now() + interval '24 hours'),
  created_at timestamptz not null default now(),
  check (analysis_expires_at > created_at)
);

create table public.dishes (
  id uuid primary key default gen_random_uuid(),
  menu_id uuid not null references public.menus (id),
  name text not null
    check (char_length(name) between 1 and 200),
  position smallint not null
    check (position between 1 and 20),
  name_key text not null
    check (char_length(name_key) >= 1),
  translations jsonb not null
    check (jsonb_typeof(translations) = 'object'),
  price numeric(10, 2)
    check (price >= 0),
  currency char(3) not null default 'JPY'
    check (currency ~ '^[A-Z]{3}$'),
  version integer not null default 1
    check (version >= 1),
  ai_result jsonb not null
    check (jsonb_typeof(ai_result) = 'object'),
  ai_model text not null
    check (char_length(ai_model) >= 1),
  prompt_version text not null
    check (char_length(prompt_version) >= 1),
  analyzed_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  unique (menu_id, position)
);

create table public.allergens (
  id smallint generated by default as identity primary key,
  code text not null unique
    check (code ~ '^[a-z][a-z_]*$'),
  name text not null unique,
  name_en text not null,
  category text not null
    check (category in ('required', 'recommended')),
  display_order smallint not null unique
    check (display_order between 1 and 29)
);

create table public.dietary_restrictions (
  id smallint primary key,
  code text not null unique
    check (code ~ '^[a-z][a-z_]*$'),
  name text not null,
  name_en text not null
);

create table public.confirmation_sessions (
  id uuid primary key default gen_random_uuid(),
  menu_id uuid not null references public.menus (id),
  restaurant_id uuid references public.restaurants (id),
  request_id uuid not null,
  publish_consent boolean not null,
  created_at timestamptz not null default now(),
  unique (menu_id, request_id)
);

create table public.confirmation_answers (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null references public.confirmation_sessions (id),
  dish_id uuid not null references public.dishes (id),
  allergen_id smallint not null references public.allergens (id),
  dish_version integer not null,
  answer text not null
    check (answer in ('contains', 'cross_contact', 'not_contains', 'unknown')),
  created_at timestamptz not null default now(),
  unique (session_id, dish_id, allergen_id)
);

create table public.confirmation_dietary_answers (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null references public.confirmation_sessions (id),
  dish_id uuid not null references public.dishes (id),
  dietary_restriction_id smallint not null references public.dietary_restrictions (id),
  dish_version integer not null,
  answer text not null
    check (answer in ('not_supported', 'supported', 'cross_contact', 'unknown')),
  created_at timestamptz not null default now(),
  unique (session_id, dish_id, dietary_restriction_id)
);

